import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
export const outputPath = resolve(root, "stray-node-cleaner.local.js");

// This fixed entry's named-import graph uses only exported declarations. Fail
// closed on other module syntax instead of maintaining a second implementation.
export async function buildTool3LocalBundle() {
    const modules = new Map();
    const chunks = [];
    async function visit(filename) {
        if (modules.has(filename)) return modules.get(filename);
        const name = `module${modules.size}`;
        modules.set(filename, name);
        let source = (await readFile(filename, "utf8")).replace(/\r\n/g, "\n");
        const imports = [...source.matchAll(/^import\s*\{([\s\S]*?)\}\s*from\s*["']([^"']+)["'];/gm)];
        for (const match of imports) {
            if (!match[2].startsWith(".")) throw new Error("Only local Tool 3 imports can be bundled.");
            const dependency = await visit(resolve(dirname(filename), match[2]));
            source = source.replace(match[0], `const {${match[1]}} = ${dependency};`);
        }
        const exports = [...source.matchAll(/^export\s+(?:async\s+)?(?:function|class|const|let)\s+(\w+)/gm)].map((match) => match[1]);
        source = source.replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let)\b)/gm, "");
        if (/^\s*(?:import|export)\s/m.test(source)) throw new Error(`Unsupported module syntax in ${filename}`);
        chunks.push(`// Source: ${relative(root, filename).replaceAll("\\", "/")}\nconst ${name} = (() => {\n${source}\nreturn { ${exports.join(", ")} };\n})();`);
        return name;
    }
    await visit(resolve(root, "stray-node-cleaner.js"));
    return `// GENERATED by node scripts/build-tool3-local.mjs — do not edit.\n// Classic script for direct file:// use; source modules remain authoritative.\n(() => {\n"use strict";\n${chunks.join("\n\n")}\n})();\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
    await writeFile(outputPath, await buildTool3LocalBundle());
}
